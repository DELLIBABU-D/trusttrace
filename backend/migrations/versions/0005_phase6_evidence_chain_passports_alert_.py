    import uuid
    for kind, table in (("duplicate", "duplicate_alerts"), ("pattern", "pattern_alerts")):
        rows = conn.execute(sa.text(f"SELECT a.id, a.review_status, a.review_note, a.reviewed_by, a.reviewed_at, u.organization_id "
                                    f"FROM {table} a JOIN users u ON u.id = a.reviewed_by WHERE a.review_status != 'open' "
                                    f"AND u.organization_id IS NOT NULL")).fetchall()
