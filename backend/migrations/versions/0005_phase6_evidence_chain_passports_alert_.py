            conn.execute(sa.text("INSERT INTO alert_reviews (id, alert_kind, alert_id, organization_id, status, note, reviewer_id, at) "
                                 "VALUES (:id, :k, :a, :o, :s, :n, :r, :t)"),
                         {"id": uuid.uuid4().hex, "k": kind, "a": r[0], "o": r[5], "s": r[1], "n": r[2] or "", "r": r[3], "t": r[4]})


