"""Sample documents for demos and tests, generated for ANY name you choose (nothing is predefined).

    python backend/manage.py make-sample-docs "Priya Sharma" demo-docs

writes resume.pdf, marksheet.pdf, marksheet_wrong_year.pdf and experience_letter.pdf. Every file is clearly marked as a
generated sample. They contain no real person's data. Use your own documents if you prefer: the checks work the same way.
"""
from __future__ import annotations

import io
from pathlib import Path

FOOTER = "SAMPLE DOCUMENT generated by TrustTrace for a demo - not a real record"


def pdf(lines: list[str]) -> bytes:
    """A minimal, valid single-page PDF with a real text layer (Helvetica)."""
    def esc(s: str) -> str:
        return s.encode("latin-1", "replace").decode("latin-1").replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
    lines = lines + ["", FOOTER]
    body = "BT /F1 11 Tf 14 TL 50 800 Td " + " ".join(f"({esc(line)}) '" for line in lines) + " ET"
    objs = [
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
        f"<< /Length {len(body.encode('latin-1', 'replace'))} >>\nstream\n{body}\nendstream",
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = io.BytesIO()
    out.write(b"%PDF-1.4\n")
    offsets = []
    for i, o in enumerate(objs, 1):
        offsets.append(out.tell())
        out.write(f"{i} 0 obj\n{o}\nendobj\n".encode("latin-1", "replace"))
    xref = out.tell()
    out.write(f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode())
    for off in offsets:
        out.write(f"{off:010d} 00000 n \n".encode())
    out.write(f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode())
    return out.getvalue()


def resume(name: str, degree: str, college: str, start: int, end: int, company: str = "", title: str = "", period: str = "",
           skills: str = "Python, SQL, FastAPI, Git") -> bytes:
    lines = [name, "Email and phone omitted in this sample", "", "EDUCATION", degree, f"{college}  {start} - {end}  CGPA: 8.4", "", "SKILLS", skills, ""]
    if company:
        lines += ["EXPERIENCE", f"{title} at {company}", period, ""]
    return pdf(lines)


def marksheet(name: str, university: str, degree: str, year: int, reg: str = "SAMPLE2026CS001") -> bytes:
    return pdf([university.upper(), "CONSOLIDATED MARK SHEET", f"Name of the Candidate : {name.upper()}", f"Register Number : {reg}",
                f"Degree : {degree}", "Branch : Computer Science and Engineering", f"Year of Passing : {year}", "CGPA : 8.40",
                "Total Marks : 3780 / 4500"])


def experience_letter(name: str, company: str, title: str, joined: str, relieved: str) -> bytes:
    return pdf([company, "EXPERIENCE CERTIFICATE", "", f"This is to certify that {name} was employed with us", f"as {title}.",
                f"Date of Joining : {joined}", f"Date of Relieving : {relieved}", "", "For " + company, "HR Manager"])


def write_set(name: str, out_dir: str, *, university: str = "Anna University", degree: str = "B.E. Computer Science and Engineering",
              start: int = 2022, end: int = 2026, company: str = "Zoho Corporation Pvt Ltd", title: str = "Software Engineer Intern",
              joined: str = "01/05/2025", relieved: str = "31/07/2025") -> list[Path]:
    """Writes a consistent set plus one marksheet with a deliberately wrong year (to demonstrate mismatch detection)."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    m_from, y_from = joined.split("/")[1], joined.split("/")[2]
    m_to, y_to = relieved.split("/")[1], relieved.split("/")[2]
    files = {
        "resume.pdf": resume(name, degree, f"{university}, Chennai", start, end, company, title, f"{m_from}/{y_from} - {m_to}/{y_to}"),
        "marksheet.pdf": marksheet(name, university, "Bachelor of Engineering", end),
        "marksheet_wrong_year.pdf": marksheet(name, university, "Bachelor of Engineering", end - 2),
        "experience_letter.pdf": experience_letter(name, company, title, joined, relieved),
    }
    paths = []
    for fname, data in files.items():
        (out / fname).write_bytes(data)
        paths.append(out / fname)
    # matching SIMULATED DigiLocker record (same details as marksheet.pdf), for manage.py load-digilocker-records
    csv_path = out / "digilocker_records.csv"
    csv_path.write_text("mobile,holder_name,issuer,doctype,title,register_number,degree,year,cgpa\n"
                        f",{name},{university},MARKSHEET,Consolidated Mark Sheet - {degree},SAMPLE2026CS001,Bachelor of Engineering,{end},8.40\n",
                        encoding="utf-8")
    paths.append(csv_path)
    return paths
